# SmartBin PostgreSQL Configuration
# Database credentials are loaded from .env

import os
from urllib.parse import urlsplit, unquote

DB_CONNECTION_MODE = os.getenv("DB_CONNECTION_MODE", "session")

if DB_CONNECTION_MODE not in ("session", "direct"):
    raise ValueError("DB_CONNECTION_MODE harus session atau direct")

DATABASE_URL = os.getenv(
    "SUPABASE_SESSION_DATABASE_URL"
    if DB_CONNECTION_MODE == "session"
    else "SUPABASE_DIRECT_DATABASE_URL"
)

if not DATABASE_URL:
    raise ValueError("Connection string Supabase belum dikonfigurasi")

parsed = urlsplit(DATABASE_URL)

if parsed.scheme not in ("postgresql", "postgres"):
    raise ValueError("Format PostgreSQL URL tidak valid")

DATABASES = {
    "default": {
        "ENGINE": "django.db.backends.postgresql",
        "NAME": unquote(parsed.path.lstrip("/")),
        "USER": unquote(parsed.username or ""),
        "PASSWORD": unquote(parsed.password or ""),
        "HOST": parsed.hostname,
        "PORT": parsed.port or 5432,
        "OPTIONS": {
            "sslmode": "require",
            "options": "-c default_transaction_read_only=on",
        },
        "CONN_MAX_AGE": 0,
    }
}



